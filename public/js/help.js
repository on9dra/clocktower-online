export function showHelp(isSt) {
  const tabs = isSt ? [['st', '說書人指南'], ['rules', '遊戲規則']] : [['rules', '遊戲規則']];
  const body = h('div', { class: 'doc' });
  const nav = h('nav', { class: 'tabs' });
  const show = key => {
    nav.querySelectorAll('.tab').forEach(b => b.classList.toggle('on', b.dataset.k === key));
    body.replaceChildren(...(key === 'st' ? ST() : [...RULES(), PLAYER()]),
      h('p', { class: 'credit' }, '角色圖示來自 game-icons.net（CC BY 3.0）。'));
  };
  tabs.forEach(([k, l]) => nav.append(h('button', { class: 'tab', 'data-k': k, onclick: () => show(k) }, l)));
  modal('規則與流程', h('div', {}, tabs.length > 1 && nav, body), { wide: true });
  show(tabs[0][0]);
}
